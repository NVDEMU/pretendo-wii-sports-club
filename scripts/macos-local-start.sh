#!/usr/bin/env bash
set -euo pipefail

# One-command local test path for macOS with Docker Desktop.
# This is intentionally a LOCAL test configuration, not public-server hosting.

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

if ! command -v docker >/dev/null 2>&1; then
  echo "Docker CLI was not found. Install Docker Desktop for Mac, then reopen Terminal." >&2
  echo "https://docs.docker.com/desktop/setup/install/mac-install/" >&2
  exit 1
fi

if ! docker info >/dev/null 2>&1; then
  echo "Docker is installed but its engine is not running. Open Docker.app and wait until it finishes starting." >&2
  exit 1
fi

if ! docker compose version >/dev/null 2>&1; then
  echo "Docker Compose is unavailable. Reinstall/update Docker Desktop for Mac." >&2
  exit 1
fi

if [[ ! -f .env ]]; then
  if ! command -v openssl >/dev/null 2>&1; then
    echo "OpenSSL is required to generate local-only random secrets." >&2
    exit 1
  fi
  kerberos_password="$(openssl rand -hex 32)"
  internal_api_token="$(openssl rand -hex 32)"
  cat > .env <<EOF
# Generated by scripts/macos-local-start.sh. Local development only.
KERBEROS_PASSWORD=$kerberos_password
SECURE_SERVER_LOCATION=localhost
SECURE_SERVER_PORT=60015
MONGO_URI=mongodb://mongo:27017/
NEX_ACCOUNTS_DATABASE=wsc
NEX_ACCOUNTS_COLLECTION=nexaccounts
WSC_INTERNAL_API_TOKEN=$internal_api_token
NEX_AUTH_PUBLIC_HOST=localhost
NEX_AUTH_PUBLIC_PORT=60014
EOF
  chmod 600 .env
  echo "Created a local .env with random development secrets (it is git-ignored)."
else
  echo "Keeping your existing .env unchanged."
fi

# Read only the expected 64-hex-character token value; never execute .env as shell code.
api_token="$(sed -n 's/^WSC_INTERNAL_API_TOKEN=//p' .env | tail -n 1)"
if [[ ! "$api_token" =~ ^[[:xdigit:]]{64}$ ]]; then
  echo "Your .env must contain WSC_INTERNAL_API_TOKEN with a 64-character hexadecimal secret." >&2
  echo "To preserve your config, this script did not overwrite .env. Review .env locally and retry." >&2
  exit 1
fi

export COMPOSE_PROJECT_NAME=wsc-local
docker compose up --build -d
docker compose ps

echo
echo "Running the internal bridge smoke test against the Compose MongoDB container..."
docker run --rm \
  --network wsc-local_default \
  -v "$ROOT_DIR/scripts/smoke_test_internal_bridge.py:/smoke.py:ro" \
  -e WSC_INTERNAL_API_TOKEN="$api_token" \
  python:3.12-alpine python /smoke.py --host localhost --port 60014

echo
echo "Local container smoke test passed."
echo "View logs:  docker compose -p wsc-local logs --tail=100 wsc-authentication wsc-secure"
echo "Stop stack: docker compose -p wsc-local down"
echo "This does NOT make the service reachable from the public Internet or a Wii U."
